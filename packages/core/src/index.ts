// packages/core — pure, deterministic domain library for Hearable Agents.
// This entry module is the public surface: it re-exports the normalized event
// schema, the adapter capabilities schema and their inferred types from
// src/events/schema.ts, and the tool classifier (src/classify/classify.ts)
// that turns observed tool calls into categories, exec kinds and repetition
// fingerprints. The classifier is what adapters use at the tool-event
// boundary; its input and output types are inferred from the zod schemas in
// src/classify/schema.ts. The lane state engine lives in src/engine/ and is
// re-exported below; the attention model and scene mapping arrive in later
// phases and must follow the same purity rules: no I/O, no
// Date.now(), no unseeded randomness, and no imports of Node's built-in
// modules or of other workspace packages.

// Scene mapping and seeded RNG (p3-t01 owns this block; later Phase 3 tasks
// must not touch it): the `LaneRender` input contract, the `SceneParams`
// output `packages/audio` renders, the pure `render` mapping, the scene
// tuning constants, and the deterministic RNG drift and QA share.
// Attention model (p4-t01 owns this block; later Phase 4 tasks consume but
// never reshape it): the pure `LaneState[]` + calm + previous state
// transition into per-lane prominence, one foreground lane and debounced
// gesture triggers per docs/STATE_ENGINE.md §Attention model.
